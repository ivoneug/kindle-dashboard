// Copies the @font-face blocks (Chakra Petch 500/700, JetBrains Mono 400, all
// inlined as woff2) out of claude-thing's device-app stylesheet, so frames use
// exactly the type the Car Thing does. Both families are OFL.
//
//   node scripts/extract-fonts.js [path/to/claude-thing]
//
// Default path: $CLAUDE_THING_DIR, else ../claude-thing-kiosk/upstream next to
// this repo.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(__dirname, '..', '..');
const root = process.argv[2] || process.env.CLAUDE_THING_DIR ||
  path.resolve(repo, '..', 'claude-thing-kiosk', 'upstream');
const src = path.join(root, 'device-app', 'src', 'styles.css');
const out = path.resolve(__dirname, '..', 'src', 'theme', 'fonts.css');

const css = fs.readFileSync(src, 'utf8');
const blocks = css.match(/@font-face\s*\{[^}]*\}/g) || [];
if (blocks.length === 0) {
  console.error(`no @font-face blocks in ${src}`);
  process.exit(1);
}
fs.writeFileSync(out,
  `/* Generated by scripts/extract-fonts.js from claude-thing device-app/src/styles.css. */\n` +
  blocks.join('\n') + '\n');
console.log(`wrote ${blocks.length} @font-face blocks → ${path.relative(repo, out)}`);
